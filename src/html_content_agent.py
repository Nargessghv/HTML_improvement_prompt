    def _validate_html_content(self, content: str) -> bool:
        """
        Validate that content is proper HTML

        Args:
            content: Content string to validate

        Returns:
            True if content appears to be valid HTML
        """
        content_lower = content.lower().strip()

        # Check for basic HTML structure
        has_doctype = "<!doctype" in content_lower or "<html" in content_lower
        has_body = "<body" in content_lower

        # Check for common HTML elements
        has_elements = any(
            tag in content_lower for tag in ["<div", "<p", "<h1", "<h2", "<h3", "<span"]
        )

        # Relaxed validation - if it has HTML structure, accept it
        has_basic_html = "<" in content and ">" in content

        # Validate Mermaid syntax if present
        if '<div class="mermaid">' in content:
            mermaid_valid = self._validate_mermaid_syntax(content)
            if not mermaid_valid:
                print("    ⚠️ Invalid Mermaid syntax detected")
                return False

        # Debug validation process
        is_valid = (has_doctype and has_body and has_elements) or (has_doctype and has_basic_html)
        
        if not is_valid:
            print(f"🔍 HTML validation failed - doctype: {has_doctype}, body: {has_body}, elements: {has_elements}, basic_html: {has_basic_html}")
            print(f"🔍 Content preview: {content[:200]}...")
        
        # Accept if it has proper structure OR basic HTML tags
        return is_valid

    def _validate_mermaid_syntax(self, html_content: str) -> bool:
        """
        Validate Mermaid diagram syntax in HTML content

        Args:
            html_content: HTML content containing Mermaid diagrams

        Returns:
            True if Mermaid syntax is valid
        """
        import re

        try:
            # Extract Mermaid diagram content
            mermaid_pattern = r'<div class="mermaid">(.*?)</div>'
            mermaid_matches = re.findall(mermaid_pattern, html_content, re.DOTALL)

            if not mermaid_matches:
                return True  # No Mermaid diagrams to validate

            for diagram_content in mermaid_matches:
                diagram_content = diagram_content.strip()

                # Common Mermaid syntax issues that cause failures
                issues = []

                # Check for HTML tags in nodes (common cause of failures)
                if re.search(r"<[^>]+>", diagram_content):
                    issues.append("HTML tags found in Mermaid nodes")

                # Check for proper diagram type declaration
                valid_starts = [
                    "graph",
                    "flowchart",
                    "timeline",
                    "pie",
                    "journey",
                    "gitgraph",
                ]
                first_line = diagram_content.split("\n")[0].strip().lower()
                if not any(first_line.startswith(start) for start in valid_starts):
                    issues.append(f"Invalid diagram type: {first_line}")

                # Check for unmatched quotes
                quote_count = diagram_content.count('"')
                if quote_count % 2 != 0:
                    issues.append("Unmatched quotes in Mermaid syntax")

                # Check for invalid arrow syntax
                invalid_arrows = ["--o>", "<--o", "--->", "<---"]
                for arrow in invalid_arrows:
                    if arrow in diagram_content:
                        issues.append(f"Invalid arrow syntax: {arrow}")

                if issues:
                    print(f"    ⚠️ Mermaid validation issues: {issues}")
                    return False

            return True

        except Exception as e:
            print(f"    ⚠️ Error validating Mermaid syntax: {e}")
            return False

    def _fix_mermaid_syntax(self, html_content: str) -> str:
        """
        Fix common Mermaid syntax issues that cause rendering failures

        Args:
            html_content: HTML content with potentially problematic Mermaid syntax

        Returns:
            HTML content with fixed Mermaid syntax
        """
        import re

        try:
            # Extract and fix each Mermaid diagram
            def fix_mermaid_diagram(match):
                diagram_content = match.group(1).strip()

                # Fix 1: Remove HTML tags and replace with simple text
                diagram_content = re.sub(r"<b>(.*?)</b>", r"\1", diagram_content)
                diagram_content = re.sub(r"<i>(.*?)</i>", r"\1", diagram_content)
                diagram_content = re.sub(r"<br\s*/?>", r"\\n", diagram_content)
                diagram_content = re.sub(r"<[^>]+>", "", diagram_content)

                # Fix 2: Ensure proper quotes around node text
                # Match patterns like A[text] and ensure quotes: A["text"]
                diagram_content = re.sub(
                    r'(\w+)\[([^"\]]+)\]',
                    lambda m: f'{m.group(1)}["{m.group(2).strip()}"]',
                    diagram_content,
                )

                # Fix 3: Replace invalid arrow types
                arrow_fixes = {
                    "--o>": "-->",
                    "<--o": "<--",
                    "--->": "-->",
                    "<---": "<--",
                    "-.o>": "-.->",
                    "=o=>": "==>",
                }
                for old_arrow, new_arrow in arrow_fixes.items():
                    diagram_content = diagram_content.replace(old_arrow, new_arrow)

                # Fix 4: Clean up excessive whitespace
                lines = diagram_content.split("\n")
                cleaned_lines = []
                for line in lines:
                    line = line.strip()
                    if line:  # Skip empty lines
                        cleaned_lines.append(line)

                diagram_content = "\n    ".join(cleaned_lines)

                return f'<div class="mermaid">\n    {diagram_content}\n</div>'

            # Apply fixes to all Mermaid diagrams
            mermaid_pattern = r'<div class="mermaid">(.*?)</div>'
            fixed_content = re.sub(
                mermaid_pattern, fix_mermaid_diagram, html_content, flags=re.DOTALL
            )

            return fixed_content

        except Exception as e:
            print(f"    ⚠️ Error fixing Mermaid syntax: {e}")
            return html_content

    def _is_html_visualization(self, content: str) -> bool:
        """Check if content is an HTML visualization"""
        return self._validate_html_content(content)

